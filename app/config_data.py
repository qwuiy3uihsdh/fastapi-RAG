"""
全局配置模块。

本模块集中存放 RAG 系统运行所需的各类参数：向量库位置、文本切分规则、
检索召回数量、模型名称以及会话配置等。其他模块通过 `import config_data as config`
统一读取，避免参数散落在各处，方便集中调整。
"""

# ---------------------------------------------------------------------------
# 去重记录文件
# ---------------------------------------------------------------------------
# 存放已入库文本 MD5 值的文本文件路径（每行一个 MD5）。
# 上传知识库前会先比对该文件，实现"同一内容不重复入库"。
md5_text = "./md5.text"


# ---------------------------------------------------------------------------
# 向量数据库（Chroma）配置
# ---------------------------------------------------------------------------
# Chroma 中的集合（collection）名称，相当于关系库里的"表名"，
# 同一 collection 下的向量才会被一起检索。
collection_name = "rag"

# Chroma 持久化目录。向量数据落盘到这里，进程重启后数据仍然存在。
persist_directory = "./chroma.db"


# ---------------------------------------------------------------------------
# 文本切分配置
# ---------------------------------------------------------------------------
# 每个文本块（chunk）的目标长度上限，单位是字符数。
chunk_size = 1000

# 相邻文本块之间的重叠字符数。保留重叠是为了避免关键语义被从中间切断，
# 导致检索时上下文丢失。
chunk_overlap = 100

# 切分时的分隔符优先级列表（从前往后依次尝试）。
# RecursiveCharacterTextSplitter 会优先在靠前的分隔符处切分，
# 这样能尽量保证切出来的块语义完整（先按段落、再按句子、最后按字符）。
# 越靠后表示"越不理想"的切分点。
separators = ["\r\n", "\r\n\r\n", "\n\n", "\n", ".", "!", "?","。","！","？"," ", ""]

# 触发文本切分的最小长度。文本长度超过该值才调用切分器，
# 短文本直接作为一个整体块入库。
max_spilt_char_number = 1000


# ---------------------------------------------------------------------------
# 检索配置
# ---------------------------------------------------------------------------
# 向量检索时召回的文档块数量（对应 Chroma retriever 的 k 参数）。
# 取回的片段越多，上下文越全，但 token 消耗和噪声也越多。
similarity_threshold = 2


# ---------------------------------------------------------------------------
# 模型配置
# ---------------------------------------------------------------------------
# 阿里云百炼（DashScope）的向量化模型名称，用于把文本转成 embedding。
embedding_model_name = "text-embedding-v3"

# 对话大模型名称，用于最终生成回答。
chat_model_name = "qwen-max"


# ---------------------------------------------------------------------------
# 会话配置
# ---------------------------------------------------------------------------
# 传给 LangChain 可运行链的配置，configurable.session_id 决定
# 使用哪一份历史对话文件（见 file_history_store.py）。
session_config = {
    "configurable": {
        "session_id": "user_001",  # 会话标识，同时用作历史记录文件名
    }
}
